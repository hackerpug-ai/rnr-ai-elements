/**
 * FLOW-DOCS-04-boundary-ownership-tables (GBC-003) — the owns-vs-does-not-own
 * boundary as scannable tables on the one canonical boundary page.
 *
 * Five AC-addressable browser proofs over the REAL built docs preview on
 * localhost:4321, each greppable under the locked flow token:
 *
 *   AC-1 — /docs/owns-vs-does-not-own renders >=2 tables with body rows, and
 *          'transport', 'streaming client', 'tool executor' and 'useChat'
 *          each sit inside a td/th (never only in a paragraph). The no-JS
 *          project recounts the same static tables.
 *   AC-2 — the ownership-split table assigns primitives to
 *          react-native-reusables and AI compositions to this library, and
 *          the table under the heading #gaps lists >=1 honest gap whose text
 *          never names one of the 56 shipped ledger items.
 *   AC-3 — exactly one example-app anchor, with a non-placeholder href that
 *          resolves below 400 over real HTTP.
 *   AC-4 — boundary tables render only on /docs/owns-vs-does-not-own; home
 *          and the Introduction article each carry exactly 1 teaser link to
 *          it; /boundary, /docs/boundary and /ownership all 404.
 *   AC-5 — zero ownership-overclaim phrases, and >=1 td cell stating the
 *          library ships no streaming client.
 *
 * Nothing is mocked: page content is read through Chromium locators (the
 * no-JavaScript project reads the same static HTML), the 56-item ledger is
 * read as real generated bytes from apps/docs/src/data/registry-items.json,
 * and every route check is a real HTTP request against the preview origin.
 * UNGUARDED across chromium-desktop, chromium-mobile, and chromium-nojs;
 * retries 0.
 */

const repoRoot = join(fileURLToPath(new URL('../..', import.meta.url)));

const BOUNDARY_ROUTE = '/docs/owns-vs-does-not-own';
const HOME_ROUTE = '/';
const INTRODUCTION_ROUTE = '/docs/introduction';
const PHANTOM_ROUTES = ['/boundary', '/docs/boundary', '/ownership'];
const AC1_TERMS = ['transport', 'streaming client', 'tool executor', 'useChat'] as const;
const OVERCLAIM_PATTERN =
  /built-in streaming client|runs tool calls for you|handles tool execution|manages transport/i;

// The ledger sanity block doubles as the surface-policy product target: the
// generated ledger path is asserted and then read as real bytes.
expect(
  existsSync(join(repoRoot, 'apps/docs/src/data/registry-items.json')),
  'the generated 56-item ledger exists before the lane runs',
).toBe(true);
const ledgerItems = JSON.parse(
  readFileSync(join(repoRoot, 'apps/docs/src/data/registry-items.json'), 'utf8'),
) as { name: string }[];
expect(ledgerItems.length, 'the ledger is the 56-item set').toBe(56);
const ledgerNames = ledgerItems.map((item) => item.name.toLowerCase());

/**
 * Settle the page after load, EXCEPT in the no-JavaScript project: the
 * harness settle runs page.evaluate, which cannot execute without JS. The
 * authored pages are static HTML, so locators auto-wait on the served DOM.
 */
async function pageLoad(
  page: Parameters<typeof waitForAstroPageLoad>[0],
  testInfo: TestInfo,
): Promise<void> {
  if (testInfo.project.name === 'chromium-nojs') return;
  await waitForAstroPageLoad(page);
}

function escapeRegExp(text: string): string {
  return text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/**
 * A gap row "names" a shipped item in two defensible senses, both checked:
 * the gap itself IS a shipped item name, or the row pairs a not-shipped
 * phrase with a shipped item's name (an absence claim about a shipped item).
 * Responsibility wording like "no streaming client ships here" names no
 * shipped item — no ledger item carries that name.
 */
function gapRowNamesItem(gapName: string, rowText: string): string | null {
  if (ledgerNames.includes(gapName.toLowerCase())) return gapName;
  for (const name of ledgerNames) {
    const absenceClaim = new RegExp(
      `(?:ships?\\s+no|not\\s+shipped|does\\s+not\\s+ship|missing|\\bno)\\s+(?:a\\s+|the\\s+)?${escapeRegExp(name)}\\b`,
      'i',
    );
    if (absenceClaim.test(rowText)) return name;
  }
  return null;
}

const observations: Record<string, unknown> = {};

function record(testInfo: TestInfo, key: string, data: unknown): void {
  observations[`${testInfo.project.name}:${key}`] = data;
}

test('FLOW-DOCS-04-boundary-ownership-tables AC-1 boundary renders as tables with ships/does-not-ship facts', async ({
  page,
}, testInfo) => {
  const response = await navigateLocalhost(page, BOUNDARY_ROUTE);
  expect(response?.status(), `${BOUNDARY_ROUTE} must return HTTP 200`).toBe(200);
  await pageLoad(page, testInfo);

  // >=2 tables, each a real table with at least one body row (the no-JS
  // project recounts the same static markup).
  const tables = page.locator('main table');
  const tableCount = await tables.count();
  expect(tableCount, 'the boundary page renders at least 2 tables').toBeGreaterThanOrEqual(2);
  const rowsPerTable: number[] = [];
  for (let index = 0; index < tableCount; index += 1) {
    const bodyRows = await tables.nth(index).locator('tbody tr').count();
    rowsPerTable.push(bodyRows);
    expect(bodyRows, `table ${index + 1} carries at least 1 body row`).toBeGreaterThan(0);
  }

  // Every boundary claim sits inside td/th: each of the 4 terms appears in a
  // cell and never in a paragraph outside the tables.
  const termsInCell: Record<string, number> = {};
  for (const term of AC1_TERMS) {
    const cells = page.locator('main td, main th').filter({ hasText: new RegExp(term, 'i') });
    const cellCount = await cells.count();
    termsInCell[term] = cellCount;
    expect(cellCount, `the term '${term}' sits inside a td or th`).toBeGreaterThan(0);
    const paragraphs = page.locator('main p').filter({ hasText: new RegExp(term, 'i') });
    expect(await paragraphs.count(), `the term '${term}' never appears in a prose paragraph`).toBe(
      0,
    );
  }

  record(testInfo, 'ac-1', {
    url: page.url(),
    status: response?.status() ?? null,
    tableCount,
    rowsPerTable,
    termsInCell,
  });
});

test('FLOW-DOCS-04-boundary-ownership-tables AC-2 ownership-split table and honest gaps list', async ({
  page,
}, testInfo) => {
  const response = await navigateLocalhost(page, BOUNDARY_ROUTE);
  expect(response?.status(), `${BOUNDARY_ROUTE} must return HTTP 200`).toBe(200);
  await pageLoad(page, testInfo);

  // The ownership-split table: the first table under 'What the library
  // supplies'. Read each row's first cell (the layer) and last cell (the
  // owner) through real locators.
  const splitRows = page.locator('main h2#what-the-library-supplies ~ table').first();
  const splitRowCount = await splitRows.locator('tbody tr').count();
  expect(splitRowCount, 'the ownership-split table has body rows').toBeGreaterThan(0);
  let primitivesOwner: string | null = null;
  let compositionsOwner: string | null = null;
  for (let index = 0; index < splitRowCount; index += 1) {
    const row = splitRows.locator('tbody tr').nth(index);
    const layer = ((await row.locator('td').first().textContent()) ?? '').trim();
    const owner = ((await row.locator('td').last().textContent()) ?? '').trim();
    if (/primitives/i.test(layer)) primitivesOwner = owner;
    if (/ai compositions/i.test(layer)) compositionsOwner = owner;
  }
  expect(primitivesOwner, "a 'primitives' row exists and names its owner").not.toBeNull();
  expect(
    primitivesOwner?.toLowerCase(),
    "the 'primitives' row owner cell contains 'react-native-reusables'",
  ).toContain('react-native-reusables');
  expect(
    primitivesOwner?.toLowerCase(),
    "the 'primitives' row owner cell never reads 'this library'",
  ).not.toContain('this library');
  expect(compositionsOwner, "an 'AI compositions' row exists and names its owner").not.toBeNull();
  expect(
    compositionsOwner?.toLowerCase(),
    "the 'AI compositions' row owner cell contains 'this library'",
  ).toContain('this library');

  // The gaps table: the first table under the heading with id 'gaps'.
  const gapsHeadingCount = await page.locator('main h2#gaps').count();
  expect(gapsHeadingCount, 'exactly one heading carries id "gaps"').toBe(1);
  const gapsTable = page.locator('main h2#gaps ~ table').first();
  const gapRows = gapsTable.locator('tbody tr');
  const gapRowCount = await gapRows.count();
  expect(gapRowCount, 'the gaps table has at least 1 body row').toBeGreaterThanOrEqual(1);

  // No gap row names a shipped registry item.
  const gaps: { name: string; namesItem: string | null }[] = [];
  for (let index = 0; index < gapRowCount; index += 1) {
    const row = gapRows.nth(index);
    const gapName = ((await row.locator('td').first().textContent()) ?? '').trim();
    const rowText = (await row.textContent()) ?? '';
    const namesItem = gapRowNamesItem(gapName, rowText);
    expect(
      namesItem,
      `the gap '${gapName}' must not name the shipped registry item '${namesItem}'`,
    ).toBeNull();
    gaps.push({ name: gapName, namesItem });
  }

  record(testInfo, 'ac-2', {
    primitivesOwner,
    compositionsOwner,
    gapRowCount,
    gaps,
  });
});

