import { spawnSync } from 'node:child_process';
import { rmSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';

const repoRoot = resolve(fileURLToPath(new URL('../../', import.meta.url)));
const biomeBin = join(repoRoot, 'node_modules/.bin/biome');

interface BiomeRun {
  status: number | null;
  output: string;
}

/**
 * FIX-FUSE-01-1 — the sprint's lint gate must actually see apps/docs. This runs the
 * real biome binary over the real apps/docs tree: it counts the files biome reports
 * checking, then proves the gate fails closed by planting a scratch file with a
 * formatting violation (double quotes vs the configured single-quote style) and
 * expecting a non-zero exit while it exists.
 *
 * Two generated paths are excluded from the include list:
 *
 * - apps/docs/src/data/gallery-manifest.json — emitted by
 *   scripts/build-gallery-manifest.ts (pnpm gallery:manifest), whose JSON.stringify
 *   output always expands arrays, so its bytes can never match biome's collapsed form
 *   until the generator formats through biome.
 * - apps/docs/.astro — Astro build output (types.d.ts, content.d.ts), regenerated by
 *   any `astro build`/`astro sync`; formatting it would make this gate flake on build
 *   order.
 */
function runBiomeCi(): BiomeRun {
  const result = spawnSync(biomeBin, ['ci', 'apps/docs'], {
    cwd: repoRoot,
    encoding: 'utf8',
    env: process.env,
    stdio: ['ignore', 'pipe', 'pipe'],
  });
  return { status: result.status, output: `${result.stdout ?? ''}${result.stderr ?? ''}` };
}

function checkedFiles(output: string): number {
  const match = output.match(/Checked (\d+) files? in/);
  if (!match) {
    throw new Error(`could not parse biome summary from output:\n${output}`);
  }
  return Number(match[1]);
}

describe('FIX-FUSE-01-1-biome-coverage', () => {
  it('biome ci apps/docs checks the real docs files and fails on a broken file', () => {
    const clean = runBiomeCi();

    // The gate must exit 0 AND check more than just itself — pre-fix it checked
    // 0 files ("No files were processed in the specified paths").
    expect(clean.status, `biome ci apps/docs exited ${clean.status}:\n${clean.output}`).toBe(0);
    const fileCount = checkedFiles(clean.output);
    expect(fileCount).toBeGreaterThan(1);

    // Negative control: a scratch file with a formatting violation must flip the
    // gate to exit 1, naming that file as the offender.
    const scratchPath = join(repoRoot, 'apps/docs/src/fix-fuse-01-1-broken-scratch.ts');
    writeFileSync(scratchPath, 'const broken = "double quotes violate the single-quote style";\n');
    try {
      const dirty = runBiomeCi();
      expect(dirty.status, `expected exit 1 with broken scratch file:\n${dirty.output}`).toBe(1);
      expect(dirty.output).toContain('fix-fuse-01-1-broken-scratch');
    } finally {
      rmSync(scratchPath, { force: true });
    }

    // Cleanup verified: removing the scratch file restores the clean gate.
    const restored = runBiomeCi();
    expect(restored.status, `gate did not recover after cleanup:\n${restored.output}`).toBe(0);
    expect(checkedFiles(restored.output)).toBe(fileCount);
  });
});
